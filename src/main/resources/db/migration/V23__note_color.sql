-- 笔记标记色（2026-09-16 用户反馈："笔记现在就是一堆文字，看着杂乱无章"）
--
-- 一条笔记可以标一个颜色（黄/绿/蓝/粉），列表里以左侧色条 + 标题颜色点显示。
-- 用途是让用户在列表里**一眼分出类别**（例如：黄=要背的、绿=懂了、蓝=待查、粉=易错），
-- 而不是靠读文字。为空 = 不标色（默认）。
--
-- 与"笔记内容里的行内高亮"（==文字==）是两件事：这里标的是**整条笔记**的类别色，
-- 行内高亮标的是正文里的重点句。两者都不影响导出（笔记本来就不进内容包）。

ALTER TABLE note ADD COLUMN color VARCHAR(8);
